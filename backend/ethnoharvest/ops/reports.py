"""PDF exports for a Harvest Passport. Content comes from passport.detail() for the requesting role, so restricted fields
(exact site) are already hidden for roles that may not see them. Every page states what the report is NOT."""
from __future__ import annotations

import io
import time
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from . import passport as pp
from .db import OpsError
from .documents import KIND_LABEL

KINDS = {
    "passport": "Harvest Passport and audit packet",
    "checklist": "Preparation checklist",
    "ledger": "Batch and inventory ledger summary",
    "quality": "Quality review checklist",
    "research": "Research and caveats summary",
    "transfer": "Transfer readiness summary",
}
FOOTER = ("Not a permit, licence, certificate, certificate of analysis, legal opinion or sustainability claim. "
          "Generated by EthnoHarvest from records entered or uploaded by users; document authenticity is not verified with issuers.")
ss = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=ss["Heading1"], fontSize=16, spaceAfter=4)
H2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=11.5, spaceBefore=10, spaceAfter=4)
P = ParagraphStyle("p", parent=ss["BodyText"], fontSize=8.8, leading=11.5)
SMALL = ParagraphStyle("s", parent=P, fontSize=7.5, leading=9.5, textColor=colors.HexColor("#555555"))


def esc(v) -> str:
    return (str(v) if v is not None else "—").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def kg(g) -> str:
    return f"{(g or 0) / 1000:,.2f} kg"


def table(rows, widths=None, head=True):
    t = Table([[Paragraph(esc(c), P) for c in r] for r in rows], colWidths=widths, repeatRows=1 if head else 0)
    st = [("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#999999")), ("VALIGN", (0, 0), (-1, -1), "TOP")]
    if head:
        st.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e6ece6")))
    t.setStyle(TableStyle(st))
    return t


def _page(synthetic: bool, title: str, role: str):
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    def draw(c, doc):
        c.saveState()
        if synthetic:
            c.setFillColor(colors.Color(0.75, 0.2, 0.2, alpha=0.14))
            c.setFont("Helvetica-Bold", 30)
            c.translate(A4[0] / 2, A4[1] / 2)
            c.rotate(35)
            c.drawCentredString(0, 0, "SYNTHETIC DEMO — NOT VALID")
            c.rotate(-35)
            c.translate(-A4[0] / 2, -A4[1] / 2)
        c.setFillColor(colors.HexColor("#444444"))
        c.setFont("Helvetica", 6.6)
        c.drawString(15 * mm, 12 * mm, FOOTER[:150])
        c.drawString(15 * mm, 9 * mm, FOOTER[150:])
        c.drawRightString(A4[0] - 15 * mm, A4[1] - 10 * mm, f"{title} · generated {stamp} for role: {role} · page {doc.page}")
        c.restoreState()
    return draw


def _head(d, title):
    out = [Paragraph(esc(title), H1),
           Paragraph(f"<b>{esc(d['code'])}</b> · <i>{esc(d['accepted_name'])}</i> · {esc(d['organ'])} · status: {esc(d['status_label'])}"
                     + (" · <font color='#b03030'><b>SYNTHETIC DEMO DATA</b></font>" if d.get("synthetic") else ""), P),
           Paragraph(f"Activity: {esc(d.get('activity'))} · Region: {esc(d.get('region_label'))} · Jurisdiction: {esc(d.get('jurisdiction'))}"
                     f" · Exact site: {esc(d.get('private_locality'))}", P),
           Paragraph(esc(d["not_a_permit"]), SMALL), Spacer(1, 6)]
    return out


def _tasks(d, only_open=False):
    ts = [t for t in d["tasks"] if not only_open or t["status"] in ("open", "in-review")]
    return table([["Task", "Owner", "Blocking", "Status", "Resolution"]] +
                 [[t["title"], t["owner_role"], "yes" if t["blocking"] else "no", t["status"], t.get("resolution") or ""] for t in ts],
                 [70 * mm, 28 * mm, 16 * mm, 18 * mm, 48 * mm])


def _prefill(d):
    pf = d.get("prefill") or {}
    rows = [["Item", "Value", "Provenance"]]
    for k, label in [("accepted_name", "Accepted name"), ("organ", "Harvested part"), ("growth_form", "Growth form"),
                     ("quota_answer", "Local harvest rate"), ("cites", "CITES")]:
        v = (pf.get(k) or {}).get("value")
        if isinstance(v, dict):
            v = ("listed, App. " + ", ".join(v.get("appendices") or [])) if v.get("listed") else v.get("status", "unknown") if v.get("status") != "available" else "not listed"
        rows.append([label, v, (pf.get(k) or {}).get("provenance", "")])
    for s in ((pf.get("studies") or {}).get("value") or []):
        rows.append(["Published study", f"{s.get('design')} · {s.get('organ')} · {s.get('citation', '')[:160]}", "prefilled-source"])
    return table(rows, [38 * mm, 112 * mm, 30 * mm])


def _lots(d):
    return table([["Lot", "Condition", "Status", "On hand", "Reserved", "Available"]] +
                 [[l["code"], l["basis"], l["status"], kg(l["on_hand_g"]), kg(l["reserved_g"]), kg(l["available_g"])] for l in d["lots"]])


def _processing(d):
    return table([["Method", "Input", "Output", "Water", "Rejected", "Waste", "Unexplained"]] +
                 [[p["method"], kg(p["in_g"]), kg(p["out_g"]), kg(p["moisture_g"]), kg(p["rejected_g"]), kg(p["waste_g"]), kg(p["unexplained_g"])]
                  for p in d["processing"]])


def _quality(d):
    lots = {l["id"]: l["code"] for l in d["lots"]}
    return table([["Lot", "Test", "Result", "Documented limit", "Limit source", "Outcome"]] +
                 [[lots.get(q["lot_id"]), q["analyte"], f"{q['result'] if q['result'] is not None else 'missing'} {q['unit'] or ''}",
                   q.get("criterion") or "none documented", q.get("criterion_source") or "", q["outcome"]] for q in d["quality_tests"]])


def _issues(d):
    return table([["Check", "Severity", "Finding"]] + [[i["category"], i["severity"], i["message"]] for i in d["issues"]],
                 [32 * mm, 22 * mm, 126 * mm])


def _docs(d):
    return table([["File", "Read as", "Status", "SHA-256", "Issuer verification"]] +
                 [[x["filename"], KIND_LABEL.get(x["doc_kind"], x["doc_kind"]), x["status"], x["sha256"][:16] + "…", "not verified"] for x in d["documents"]])


def build(ws: str, role: str, pid: str, kind: str) -> tuple[bytes, str]:
    if kind not in KINDS:
        raise OpsError(404, "unknown report")
    d = pp.detail(ws, role, pid)
    title = KINDS[kind]
    s = _head(d, title)
    if kind in ("passport", "checklist"):
        s += [Paragraph("What public sources say", H2), _prefill(d)]
    if kind == "checklist":
        s += [Paragraph("Open preparation tasks", H2), _tasks(d, only_open=True),
              Paragraph("Each task names who should act. Waived tasks keep their reason in the audit trail.", SMALL)]
    if kind == "passport":
        s += [Paragraph("Tasks", H2), _tasks(d), Paragraph("Collections", H2),
              table([["Date", "Collector", "Reported", "Condition"]] + [[h["date"], h["collector"], f"{h['qty_original']} {h['unit_original']}", h["basis"]]
                                                                       for h in d["harvest_events"]])]
    if kind in ("passport", "ledger"):
        s += [Paragraph("Lots", H2), _lots(d), Paragraph("Processing and mass balance", H2), _processing(d),
              Paragraph("Fresh and dry mass are never summed. Unexplained mass is a reconciliation gap to explain, not an accusation.", SMALL)]
    if kind == "ledger":
        from .ledger import lot_ledger
        for l in d["lots"]:
            led = lot_ledger(ws, l["id"])
            s += [Paragraph(f"Ledger · {esc(l['code'])}", H2),
                  table([["#", "Event", "Change", "Balance", "By", "Reason"]] +
                        [[e["seq"], e["kind"], kg(e["qty_g"]) if e["qty_g"] else "", kg(e["running_g"]), e["actor_role"], e.get("reason") or ""]
                         for e in led["events"]])]
    if kind in ("passport", "quality", "transfer"):
        s += [Paragraph("Laboratory results", H2), _quality(d),
              Paragraph("Comparisons use the limit documented by the user. EthnoHarvest does not certify quality or safety.", SMALL)]
    if kind in ("passport", "quality", "transfer"):
        s += [Paragraph("Documents and cross-document checks", H2), _docs(d), Spacer(1, 4), _issues(d)]
    if kind == "quality":
        open_q = [t for t in d["tasks"] if t["kind"] in ("quality", "document") and t["status"] in ("open", "in-review")]
        s += [Paragraph("Open quality items", H2), table([["Task", "Owner", "Blocking"]] + [[t["title"], t["owner_role"], "yes" if t["blocking"] else "no"] for t in open_q])]
    if kind == "transfer":
        s += [Paragraph("Shipments", H2)]
        for sh in d["shipments"]:
            s += [Paragraph(f"{kg(sh['qty_g'])} to {esc(sh['destination_country'])} · {esc(sh['status'])}", P),
                  table([["Checklist item", "Status", "Note"]] + [[c["item"], "done" if c["ok"] else "open", c.get("note") or ""] for c in sh["checklist"]])]
        s += [Paragraph("Human decisions", H2),
              table([["Target", "Decision", "By role", "Reason"]] + [[r["target"], r["decision"], r["role"], r["reason"]] for r in d["reviews"]]),
              Paragraph("Blocking items still open", H2), _tasks({"tasks": [t for t in d["tasks"] if t["blocking"]]}, only_open=True),
              Paragraph("Ready for transfer only when an authorised person has recorded an approval and no blocking item is open. "
                        "This summary does not replace export or CITES documents.", SMALL)]
    if kind in ("research", "passport"):
        cz = (d.get("cautions") or {})
        if not cz:
            try:
                from .cautions import cautions_for
                cz = cautions_for(ws, role, pid, refresh=False)
            except Exception:  # noqa: BLE001 - research is optional in the packet
                cz = {"status": "research not available", "cards": []}
        s += [Paragraph("Species- and part-specific cautions", H2), Paragraph(f"Status: {esc(cz.get('status'))}", SMALL)]
        for c in cz.get("cards", []):
            s += [Paragraph(f"<b>{esc(c['issue'])}</b> ({esc(c['evidence_kind'])}; applies: {esc(c['applicability'])}; review: {esc(c['human_review_status'])})", P),
                  Paragraph(esc(c["why_it_matters"]), P), Paragraph("Next: " + esc(c["recommended_next"]), P),
                  Paragraph("Sources: " + "; ".join(esc(x["title"]) + (f" ({esc(x['url'])})" if x.get("url") else "") for x in c["sources"]), SMALL),
                  Spacer(1, 4)]
    if kind == "passport":
        s += [Paragraph("Audit trail", H2),
              table([["When (UTC)", "Role", "Entity", "Action"]] +
                    [[datetime.fromtimestamp(a["ts"], timezone.utc).strftime("%Y-%m-%d %H:%M"), a["actor_role"], a["entity"], a["action"]]
                     for a in d["audit_trail"]])]
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=16 * mm, bottomMargin=20 * mm,
                            title=f"{d['code']} {title}", author="EthnoHarvest")
    doc.build(s, onFirstPage=_page(bool(d.get("synthetic")), title, role), onLaterPages=_page(bool(d.get("synthetic")), title, role))
    return buf.getvalue(), f"{d['code']}-{kind}-{time.strftime('%Y%m%d')}.pdf"

